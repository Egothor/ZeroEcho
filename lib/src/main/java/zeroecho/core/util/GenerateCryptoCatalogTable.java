package zeroecho.core.util;

import java.io.Writer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashSet;
import java.util.List;
import java.util.OptionalInt;
import java.util.Set;
import java.util.SortedSet;
import java.util.TreeSet;

import zeroecho.core.Capability;
import zeroecho.core.CryptoAlgorithm;
import zeroecho.core.CryptoAlgorithms;
import zeroecho.core.ParameterSetDescriptor;
import zeroecho.core.SecurityLevel;
import zeroecho.core.TemplateParameter;
import zeroecho.sdk.util.BouncyCastleActivator;

/**
 * Emits an HTML fragment with a table that summarizes discovered cryptographic
 * algorithms. The table includes subcolumns for algorithm families and key
 * usages found in capabilities.
 *
 * <h2>Columns</h2>
 * <ul>
 * <li>Algorithm ID</li>
 * <li>Display Name</li>
 * <li>Family:* (one column per family present)</li>
 * <li>Key usage:* (one column per role present)</li>
 * <li>Parameter sets (from {@link zeroecho.core.CryptoAlgorithm#parameterSets()})</li>
 * </ul>
 *
 * <p>
 * Usage:
 * </p>
 * <pre>{@code
 *   java zeroecho.tools.GenerateCryptoCatalogTable /abs/path/to/table.html
 * }</pre>
 */
public final class GenerateCryptoCatalogTable {

    /**
     * Generates a standalone HTML fragment (no &lt;html&gt; or &lt;head&gt;) to the
     * given file.
     *
     * @param args the first argument must be the output file path for the generated
     *             fragment
     * @throws Exception if writing fails or discovery finds invalid providers
     */
    public static void main(String[] args) throws Exception { // NOPMD
        if (args.length != 1) { // NOPMD
            System.err.println("Expected 1 argument: output fragment path");
            System.exit(2);
        }

        BouncyCastleActivator.init();

        Path out = Path.of(args[0]);
        Path parent = out.getParent();
        if (parent != null) {
            Files.createDirectories(parent);
        }

        Set<String> algorithmIds = CryptoAlgorithms.available();
        validate(algorithmIds);

        // Enumerate subcolumns actually present.
        SortedSet<String> families = new TreeSet<>();
        SortedSet<String> roles = new TreeSet<>();
        for (String algorithmId : algorithmIds) {
            CryptoAlgorithm a = CryptoAlgorithms.require(algorithmId);
            for (Capability c : a.listCapabilities()) {
                families.add(c.family().name());
                roles.add(c.role().name());
            }
        }

        try (Writer w = Files.newBufferedWriter(out)) {
            // Optional minimal style and anchor for local TOC links.
            w.write("<!-- BEGIN: generated by GenerateCryptoCatalogTable -->\n");
            w.write("<p id=\"crypto-catalog-desc\" class=\"sr-only\">");
            w.write("Table of registered cryptographic algorithms with grouped columns for families and key usages.");
            w.write("</p>\n");

            // Open table
            w.write("<table class=\"zecat\" aria-describedby=\"crypto-catalog-desc\">");
            w.write("<caption>Registered cryptographic algorithms</caption>");

            // THEAD row 1: group headers
            w.write("<thead><tr>");
            w.write("<th scope=\"col\" rowspan=\"2\" class=\"id-col\">Algorithm ID</th>");
            w.write("<th scope=\"col\" rowspan=\"2\" class=\"display-col\">Display Name</th>");
            w.write("<th class=\"group\" colspan=\"" + families.size() + "\">Family</th>");
            w.write("<th class=\"group\" colspan=\"" + roles.size() + "\">Key usage</th>");
            w.write("<th scope=\"col\" rowspan=\"2\" class=\"paramsets-col\">Parameter sets</th>");
            w.write("</tr>");

            // THEAD row 2: subheaders (vertical labels)
            w.write("<tr>");
            int fi = 0;
            for (String f : families) {
                String cls = "vcol narrow fam" + (fi == 0 ? " fam-first" : "");
                w.write("<th scope=\"col\" class=\"" + cls + "\"><span class=\"vlabel\">" + esc(f) + "</span></th>");
                fi++;
            }
            int ri = 0;
            for (String r : roles) {
                String cls = "vcol narrow usage" + (ri == 0 ? " usage-first" : "");
                w.write("<th scope=\"col\" class=\"" + cls + "\"><span class=\"vlabel\">" + esc(r) + "</span></th>");
                ri++;
            }
            w.write("</tr></thead>");

            // TBODY
            w.write("<tbody>");
            for (String id : algorithmIds) {
                CryptoAlgorithm a = CryptoAlgorithms.require(id);

                Set<String> famHit = new HashSet<>(); // NOPMD
                Set<String> roleHit = new HashSet<>(); // NOPMD
                for (Capability c : a.listCapabilities()) {
                    famHit.add(c.family().name());
                    roleHit.add(c.role().name());
                }

                w.write("<tr>");
                w.write("<td class=\"zetag id-td\"><code>" + esc(a.id()) + "</code></td>");
                w.write("<td class=\"display-td\">" + esc(a.displayName()) + "</td>");

                int i = 0;
                for (String f : families) {
                    String cls = "zecenter narrow fam-td" + (i == 0 ? " fam-first-td" : "");
                    w.write("<td class=\"" + cls + "\">" + (famHit.contains(f) ? "&#10003;" : "") + "</td>");
                    i++;
                }
                int j = 0;
                for (String r : roles) {
                    String cls = "zecenter narrow usage-td" + (j == 0 ? " usage-first-td" : "");
                    w.write("<td class=\"" + cls + "\">" + (roleHit.contains(r) ? "&#10003;" : "") + "</td>");
                    j++;
                }
                w.write("<td class=\"paramsets-td\">" + renderParamSets(a.parameterSets()) + "</td>");
                w.write("</tr>");
            }
            w.write("</tbody></table>\n");
            w.write("<!-- END: generated by GenerateCryptoCatalogTable -->\n");
        }
    }

    private static String renderParamSets(List<ParameterSetDescriptor<? extends zeroecho.core.spec.AlgorithmKeySpec>> sets) {
        if (sets.isEmpty()) {
            return "<span class=\"no-paramsets\">—</span>";
        }
        StringBuilder sb = new StringBuilder(256);
        for (ParameterSetDescriptor<?> d : sets) {
            if (d instanceof ParameterSetDescriptor.Concrete<?> c) {
                sb.append("<div class=\"param-set concrete\"><code>").append(esc(c.id()))
                        .append("</code> <small class=\"sec-level\">")
                        .append(esc(secLevelLabel(c.securityLevel()))).append("</small></div>");
            } else if (d instanceof ParameterSetDescriptor.Template<?> t) {
                sb.append("<div class=\"param-set template\"><code>").append(esc(t.id()))
                        .append("</code> <small class=\"sec-level template-marker\"><em>template</em>(");
                boolean first = true;
                for (TemplateParameter p : t.parameters()) {
                    if (!first) { sb.append(", "); }
                    sb.append(esc(p.name())).append(": ").append(esc(p.type().getSimpleName()));
                    first = false;
                }
                sb.append(")</small></div>");
            }
        }
        return sb.toString();
    }

    private static String secLevelLabel(SecurityLevel level) {
        OptionalInt nist = level.nistLevel();
        if (nist.isPresent()) {
            return "L" + nist.getAsInt() + " / " + level.classicalBits() + "-bit";
        }
        return level.classicalBits() + "-bit";
    }

    private static void validate(Set<String> algorithmIds) {
        StringBuilder sb = null;
        for (String algorithmId : algorithmIds) {
            CryptoAlgorithm a = CryptoAlgorithms.require(algorithmId);
            boolean hasCaps = !a.listCapabilities().isEmpty();
            boolean hasKeyOperations = !a.keyOperations().isEmpty();
            if (!hasCaps && !hasKeyOperations) {
                if (sb == null) {
                    sb = new StringBuilder(); // NOPMD
                }
                sb.append("Algorithm ").append(a.id()).append(" has no capabilities nor key builders.\n");
            }
        }
        if (sb != null) {
            throw new IllegalStateException(sb.toString());
        }
    }

    private static String esc(String v) {
        if (v == null) {
            return "";
        }
        return v.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    }

    private GenerateCryptoCatalogTable() {
        /* no instances */ }
}
