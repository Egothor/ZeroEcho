package zeroecho.core.alg.xwing;

import java.security.KeyPair;
import java.security.PrivateKey;
import java.security.PublicKey;
import java.security.SecureRandom;

import java.util.List;

import zeroecho.core.ParameterSetDescriptor;
import zeroecho.core.SecurityLevel;

import org.bouncycastle.crypto.AsymmetricCipherKeyPair;
import org.bouncycastle.pqc.crypto.xwing.XWingKeyGenerationParameters;
import org.bouncycastle.pqc.crypto.xwing.XWingKeyPairGenerator;
import org.bouncycastle.pqc.crypto.xwing.XWingPrivateKeyParameters;
import org.bouncycastle.pqc.crypto.xwing.XWingPublicKeyParameters;

import zeroecho.core.AlgorithmFamily;
import zeroecho.core.KeyUsage;
import zeroecho.core.alg.AbstractCryptoAlgorithm;
import zeroecho.core.alg.common.agreement.KemMessageAgreementAdapter;
import zeroecho.core.context.KemContext;
import zeroecho.core.context.MessageAgreementContext;
import zeroecho.core.spec.VoidSpec;

/**
 * Concrete {@link zeroecho.core.CryptoAlgorithm} for the X-Wing hybrid
 * post-quantum key encapsulation mechanism.
 *
 * <h2>Overview</h2>
 * <p>
 * X-Wing combines X25519 (classical Diffie–Hellman over Curve25519) and
 * ML-KEM-768 (post-quantum lattice-based KEM) into a single hybrid KEM per
 * <a href="https://datatracker.ietf.org/doc/draft-connolly-cfrg-xwing-kem/">
 * draft-connolly-cfrg-xwing-kem</a>. It provides security if either component
 * is secure, offering a smooth migration path to post-quantum cryptography.
 * </p>
 *
 * <h2>Implementation</h2>
 * <p>
 * Because BouncyCastle 1.86 has no JCA provider binding for X-Wing, this
 * implementation uses the low-level BC API ({@code pqc.crypto.xwing.*})
 * directly. Key pairs are generated by {@link XWingKeyPairGenerator} and
 * wrapped in package-private {@link XWingPublicKey} / {@link XWingPrivateKey}
 * holders for use within the ZeroEcho context model.
 * </p>
 *
 * <h2>Capabilities</h2>
 * <ul>
 * <li>{@link KeyUsage#ENCAPSULATE}: generates a fresh shared secret and its
 * encapsulation from a recipient {@link PublicKey}.</li>
 * <li>{@link KeyUsage#DECAPSULATE}: recovers the shared secret from an
 * encapsulated ciphertext using a {@link PrivateKey}.</li>
 * <li>{@link KeyUsage#AGREEMENT} (message-style): KEM adapter for
 * initiator/responder flows using the above KEM operations.</li>
 * </ul>
 *
 * <h2>Key generation</h2>
 * <p>
 * X-Wing has no selectable parameters. Use {@link XWingKeyGenSpec#DEFAULT} as the
 * key generation spec. The private key is stored as its 32-byte seed; the
 * public key is stored as its raw encoding.
 * </p>
 *
 * <h2>Thread-safety</h2>
 * <p>
 * {@code XWingAlgorithm} instances are immutable and safe to share. Created
 * {@link KemContext} objects are not thread-safe.
 * </p>
 *
 * @since 1.0
 */
public final class XWingAlgorithm extends AbstractCryptoAlgorithm {

    private static final List<ParameterSetDescriptor<? extends zeroecho.core.spec.AlgorithmKeySpec>> PARAMETER_SETS =
            ParameterSetDescriptor.snapshot(createParameterSets());

    /**
     * Creates and wires the X-Wing algorithm with all its capabilities and the
     * key-pair generator.
     */
    public XWingAlgorithm() {
        super("X-Wing", "X-Wing");

        capability(AlgorithmFamily.KEM, KeyUsage.ENCAPSULATE, KemContext.class, PublicKey.class, VoidSpec.class,
                (PublicKey k, VoidSpec s) -> new XWingKemContext(this, k), () -> VoidSpec.INSTANCE);

        capability(AlgorithmFamily.KEM, KeyUsage.DECAPSULATE, KemContext.class, PrivateKey.class, VoidSpec.class,
                (PrivateKey k, VoidSpec s) -> new XWingKemContext(this, k), () -> VoidSpec.INSTANCE);

        capability(AlgorithmFamily.AGREEMENT, KeyUsage.AGREEMENT, MessageAgreementContext.class, PublicKey.class,
                VoidSpec.class,
                (PublicKey recipient, VoidSpec spec) -> KemMessageAgreementAdapter.builder()
                        .upon(new XWingKemContext(this, recipient)).asInitiator().build(),
                () -> VoidSpec.INSTANCE);

        capability(AlgorithmFamily.AGREEMENT, KeyUsage.AGREEMENT, MessageAgreementContext.class, PrivateKey.class,
                VoidSpec.class,
                (PrivateKey myPriv, VoidSpec spec) -> KemMessageAgreementAdapter.builder()
                        .upon(new XWingKemContext(this, myPriv)).asResponder().build(),
                () -> VoidSpec.INSTANCE);

        registerAsymmetricKeyPairGenerator(XWingKeyGenSpec.class, spec -> {
            XWingKeyPairGenerator gen = new XWingKeyPairGenerator();
            gen.init(new XWingKeyGenerationParameters(new SecureRandom()));
            AsymmetricCipherKeyPair pair = gen.generateKeyPair();
            XWingPublicKeyParameters pub = (XWingPublicKeyParameters) pair.getPublic();
            XWingPrivateKeyParameters priv = (XWingPrivateKeyParameters) pair.getPrivate();
            return new KeyPair(new XWingPublicKey(pub.getEncoded()), new XWingPrivateKey(priv.getSeed()));
        }, () -> XWingKeyGenSpec.DEFAULT);

        // X-Wing keys use RAW encoding — no standard JCA KeyFactory available.
        registerPublicKeyImporter(XWingPublicKeySpec.class, spec -> new XWingPublicKey(spec.raw()));
        registerPrivateKeyImporter(XWingPrivateKeySpec.class, spec -> new XWingPrivateKey(spec.rawSeed()));
    }

    @Override
    public List<ParameterSetDescriptor<? extends zeroecho.core.spec.AlgorithmKeySpec>> parameterSets() {
        return PARAMETER_SETS;
    }

    private static List<ParameterSetDescriptor<? extends zeroecho.core.spec.AlgorithmKeySpec>> createParameterSets() {
        return List.of(
            new ParameterSetDescriptor.Concrete<>("X-Wing", "X-Wing (ML-KEM-768 + X25519, NIST Level 3)", SecurityLevel.nist(3, 192), XWingKeyGenSpec.DEFAULT)
        );
    }

}
