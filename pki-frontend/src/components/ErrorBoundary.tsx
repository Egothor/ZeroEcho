import { Component, type ErrorInfo, type ReactNode } from 'react';
import { Alert, AlertTitle, Box, Button } from '@mui/material';

interface Props {
  readonly children: ReactNode;
}
interface State {
  readonly error: Error | null;
}

/** Top-level error boundary: contains render failures without leaking a blank page. */
export class ErrorBoundary extends Component<Props, State> {
  state: State = { error: null };

  static getDerivedStateFromError(error: Error): State {
    return { error };
  }

  componentDidCatch(error: Error, info: ErrorInfo): void {
    // Diagnostics only — never send SPA errors anywhere the operator did not configure.
    console.error('Unhandled UI error', error, info.componentStack);
  }

  render(): ReactNode {
    const { error } = this.state;
    if (!error) return this.props.children;
    return (
      <Box sx={{ p: 4, maxWidth: 720, mx: 'auto' }}>
        <Alert
          severity="error"
          action={
            <Button color="inherit" size="small" onClick={() => this.setState({ error: null })}>
              Retry
            </Button>
          }
        >
          <AlertTitle>Something went wrong</AlertTitle>
          {error.message}
        </Alert>
      </Box>
    );
  }
}
