package zeroecho.pki.server.schema;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.charset.StandardCharsets;
import java.util.List;

import tools.jackson.core.JsonGenerator;
import tools.jackson.core.json.JsonFactory;

import zeroecho.pki.server.schema.OperationParameterSchema.FieldSpec;
import zeroecho.pki.server.schema.OperationParameterSchema.OperationSpec;

/**
 * Build-time generator for complete JSON and TypeScript catalog projections.
 *
 * <p>Invoked by the {@code generateSchema} Gradle task. Accepts the output file path
 * as its first argument and an optional TypeScript output path as its second.
 * Writes UTF-8 artifacts containing every operation, including unavailable entries.</p>
 */
public final class GenerateOperationSchema {
    private static final int TYPESCRIPT_ARGUMENT_COUNT = 2;

    /**
     * Writes the requested catalog artifacts.
     * @param args JSON output path followed by an optional TypeScript output path
     * @throws IOException if either artifact cannot be written
     */
    public static void main(String[] args) throws IOException {
        if (args.length < 1 || args.length > TYPESCRIPT_ARGUMENT_COUNT) {
            throw new IllegalArgumentException("Usage: GenerateOperationSchema <json-output> [typescript-output]");
        }
        Path outputPath = Path.of(args[0]);
        Files.createDirectories(outputPath.getParent());
        byte[] json = serialize(OperationParameterSchemas.all());
        Files.write(outputPath, json);
        if (args.length == TYPESCRIPT_ARGUMENT_COUNT) {
            Path typescript = Path.of(args[1]);
            Files.createDirectories(typescript.getParent());
            Files.writeString(typescript, "// Generated by :pki-server:generateSchema. Do not edit.\n"
                    + "export const OPERATION_SCHEMA = " + new String(json, StandardCharsets.UTF_8)
                    + " as const;\nexport type OperationId = typeof OPERATION_SCHEMA[number]['operationId'];\n", StandardCharsets.UTF_8);
        }
        System.out.println("Generated " + OperationParameterSchemas.all().size()
                + " operation schemas → " + outputPath);
    }

    /**
     * Serializes an operation schema list to a UTF-8 JSON byte array.
     * @param operations ordered schemas to serialize
     * @return JSON array containing the supplied schemas and known catalog metadata
     * @throws IOException if JSON serialization fails
     */
    public static byte[] serialize(List<OperationSpec> operations) throws IOException {
        JsonFactory factory = JsonFactory.builder().build();
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        try (JsonGenerator gen = factory.createGenerator(out)) {
            gen.writeStartArray();
            for (OperationSpec op : operations) {
                writeOperation(gen, op);
            }
            gen.writeEndArray();
        }
        return out.toByteArray();
    }

    private static void writeOperation(JsonGenerator gen, OperationSpec op) throws IOException {
        gen.writeStartObject();
        gen.writeStringProperty("operationId", op.operationId());
        gen.writeStringProperty("permissionAction", op.permissionAction());
        gen.writeStringProperty("permissionResourceType", op.permissionResourceType());
        OperationDescriptorCatalog.Entry entry = OperationDescriptorCatalog.current().find(op.operationId()).orElse(null);
        if (entry != null) {
            gen.writeBooleanProperty("available", entry.available());
            gen.writeStringProperty("family", entry.security().family().name());
            gen.writeBooleanProperty("mutating", entry.security().mutating());
            gen.writeStringProperty("approval", entry.security().approvalCategory().name());
            gen.writeStringProperty("dataView", entry.security().dataView().name());
            gen.writeStringProperty("title", entry.presentation().title());
            gen.writeStringProperty("summary", entry.presentation().summary());
            gen.writeStringProperty("nav", entry.presentation().nav());
            gen.writeStringProperty("scope", entry.presentation().transport().scope());
            gen.writeStringProperty("authorityFrom", entry.presentation().transport().authorityFrom());
        }
        gen.writeName("fields");
        gen.writeStartArray();
        for (FieldSpec field : op.fields()) {
            writeField(gen, field, entry == null ? null : entry.presentation().transport().fields().get(field.name()));
        }
        gen.writeEndArray();
        gen.writeEndObject();
    }

    private static void writeField(JsonGenerator gen, FieldSpec field,
            OperationDescriptorCatalog.FieldSemantics semantics) throws IOException {
        gen.writeStartObject();
        gen.writeStringProperty("name", field.name());
        gen.writeStringProperty("type", field.type().name().toLowerCase(java.util.Locale.ROOT).replace('_', '-'));
        gen.writeBooleanProperty("required", field.required());
        gen.writeName("choices");
        gen.writeStartArray();
        for (String choice : field.choices()) {
            gen.writeString(choice);
        }
        gen.writeEndArray();
        if (semantics != null) {
            gen.writeStringProperty("semanticType", semantics.type());
            gen.writeStringProperty("ref", semantics.ref());
            gen.writeBooleanProperty("allowNew", semantics.allowNew());
            gen.writeBooleanProperty("hidden", semantics.hidden());
            gen.writeBooleanProperty("readOnly", semantics.readOnly());
            gen.writeStringProperty("label", semantics.label());
            gen.writeStringProperty("help", semantics.help());
            gen.writeStringProperty("placeholder", semantics.placeholder());
        }
        gen.writeEndObject();
    }

    private GenerateOperationSchema() {
    }
}
