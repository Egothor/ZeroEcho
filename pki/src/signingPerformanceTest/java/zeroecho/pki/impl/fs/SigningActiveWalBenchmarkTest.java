package zeroecho.pki.impl.fs;

import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Files;
import java.nio.file.Path;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** Fast fake-force smoke coverage for the opt-in active-WAL characterization. */
final class SigningActiveWalBenchmarkTest {
    @Test
    void fakeForceSmokeProducesBoundedVersionedReport(@TempDir Path temporary) throws Exception {
        Path output = temporary.resolve("result.json");
        SigningActiveWalBenchmark.main(new String[] { "--warmupSeconds=0",
                "--durationSeconds=1", "--rate=100", "--fakeForce=true",
                "--output=" + output, "--workRoot=" + temporary.resolve("work") });
        String json = Files.readString(output);
        assertTrue(json.contains("\"schema\":\"zeroecho-active-wal-characterization-v1\""));
        assertTrue(json.contains("\"payloadBytes\":1024"));
        assertTrue(json.contains("\"scheduled\":100"));
        assertTrue(json.contains("\"rejected\":0"));
    }
}
